import {
  boardCatalogEntry,
  type EsphomeDeviceBuilderConfig,
} from "@nexternel/domain";
import { installationMqttRoot } from "../../migrate/align-mqtt-topics.js";
import {
  appendComponentYaml,
  emptyGeneratorParts,
  renderI2cSection,
  renderOneWireSection,
  renderUartSection,
} from "./component-generators.js";
import { resolveBuilderSlug } from "./validate.js";

function yamlQuote(value: string): string {
  if (/^[a-zA-Z0-9 _.-]+$/.test(value)) return `"${value}"`;
  return JSON.stringify(value);
}

function platformBlock(config: EsphomeDeviceBuilderConfig): string {
  const board = boardCatalogEntry(config.boardId);
  if (!board) throw new Error(`Unknown board: ${config.boardId}`);
  if (config.platform === "esp8266") {
    return `esp8266:
  board: ${board.esphomeBoard}
  framework:
    version: recommended`;
  }
  return `esp32:
  board: ${board.esphomeBoard}
  framework:
    type: arduino`;
}

function installationTimezone(): string {
  const tz = process.env.TZ?.trim();
  return tz && tz.includes("/") ? tz : "Europe/London";
}

function otaLines(password?: string): string[] {
  const lines = ["ota:", "  - platform: esphome"];
  const trimmed = password?.trim();
  if (trimmed) lines.push(`    password: ${JSON.stringify(trimmed)}`);
  lines.push("");
  return lines;
}

export type GenerateEsphomeYamlOptions = {
  /** Kept so a board that already checks an update password can still be installed. */
  otaPassword?: string;
};

/**
 * Generate ESPHome YAML for a managed device.
 * Wi-Fi and MQTT credentials use server-side secrets — not embedded in the form.
 */
export function generateEsphomeYaml(
  config: EsphomeDeviceBuilderConfig,
  options?: GenerateEsphomeYamlOptions
): string {
  const slug = resolveBuilderSlug(config);
  const board = boardCatalogEntry(config.boardId);
  if (!board) throw new Error(`Unknown board: ${config.boardId}`);

  const mqttRoot = installationMqttRoot();
  const mqttTopicPrefix = `${mqttRoot}/${slug}`;
  const displayName = config.displayName.trim();

  const parts = emptyGeneratorParts();
  for (const component of config.components) {
    appendComponentYaml(parts, slug, displayName, component);
  }

  const lines = [
    "# Nexternel managed device — generated by Device Builder.",
    "# Advanced users may edit via Devices → Advanced; YAML may become authoritative.",
    `# Device: ${displayName}`,
    "",
    "substitutions:",
    `  device_name: ${slug}`,
    `  friendly_name: ${yamlQuote(displayName)}`,
    `  mqtt_topic_prefix: ${mqttTopicPrefix}`,
    "",
    "esphome:",
    `  name: "\${device_name}"`,
    `  friendly_name: "\${friendly_name}"`,
    "",
    platformBlock(config),
    "",
    "logger:",
    "",
    "packages:",
    "  nexternel: !include packages/nexternel-device.yaml",
    "",
    ...otaLines(options?.otaPassword),
    "wifi:",
    "  ssid: !secret wifi_ssid",
    "  password: !secret wifi_password",
    "",
    "captive_portal:",
    "",
    "mqtt:",
    "  broker: !secret mqtt_broker",
    "  port: 1883",
    "  username: !secret mqtt_username",
    "  password: !secret mqtt_password",
    `  topic_prefix: \${mqtt_topic_prefix}`,
    "  discovery: false",
    "",
  ];

  const i2cLines = renderI2cSection(parts.i2cBuses);
  if (i2cLines.length > 0) {
    lines.push("i2c:", ...i2cLines, "");
  }
  const oneWireLines = renderOneWireSection(parts.oneWirePins);
  if (oneWireLines.length > 0) {
    lines.push("one_wire:", ...oneWireLines, "");
  }
  const uartLines = renderUartSection(parts.uartBlocks);
  if (uartLines.length > 0) {
    lines.push("uart:", ...uartLines, "");
  }
  if (parts.needsTime) {
    lines.push(
      "time:",
      "  - platform: sntp",
      "    id: sntp_time",
      `    timezone: ${installationTimezone()}`,
      ""
    );
  }
  if (parts.sensorBlocks.length > 0) {
    lines.push("sensor:", ...parts.sensorBlocks, "");
  }
  if (parts.switchBlocks.length > 0) {
    lines.push("switch:", ...parts.switchBlocks, "");
  }

  return lines.join("\n").trimEnd() + "\n";
}

export function builderYamlFileName(config: EsphomeDeviceBuilderConfig): string {
  return `${resolveBuilderSlug(config)}.yaml`;
}

export function builderYamlStem(config: EsphomeDeviceBuilderConfig): string {
  return resolveBuilderSlug(config);
}
